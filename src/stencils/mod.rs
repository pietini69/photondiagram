use crate::model::{ConnectionPort, DiagramShape, PortDir, PrimOp};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum StencilCategory {
    Electrical,     // Sähkö- ja elektroniikkakaaviot (IEC/IEEE)
    BuildingElec,   // Rakennussähkö (SFS pohjapiirustusmerkit)
    FloorStructure, // Pohjapiirustus: Seinät, ovet, ikkunat, mitat
    FloorFurniture, // Pohjapiirustus: LVI, keittiö, sauna, kalusteet
    FlowAndNet,     // Vuokaaviot, PLC-automaatio & verkkolaitteet
    ImportedVisio(String), // Tuodut .vssx / .vsdx Visio-muodot (kirjaston nimi)
}

impl StencilCategory {
    pub fn built_in_categories() -> [Self; 5] {
        [
            Self::Electrical,
            Self::BuildingElec,
            Self::FloorStructure,
            Self::FloorFurniture,
            Self::FlowAndNet,
        ]
    }

    pub fn is_imported(&self) -> bool {
        matches!(self, Self::ImportedVisio(_))
    }

    pub fn title(&self) -> String {
        match self {
            Self::Electrical => "⚡ Sähkö & Elektroniikka (IEC)".to_string(),
            Self::BuildingElec => "🔌 Rakennussähkö (SFS)".to_string(),
            Self::FloorStructure => "🏠 Pohjapiirustus: Rakenteet".to_string(),
            Self::FloorFurniture => "🛋️ Pohjapiirustus: LVI & Kalusteet".to_string(),
            Self::FlowAndNet => "📊 Vuokaaviot & Automaatio".to_string(),
            Self::ImportedVisio(name) => {
                if name.is_empty() || name == "default" {
                    "📦 Tuodut Visio-symbolit (.vssx)".to_string()
                } else {
                    format!("📦 Visio: {}", name)
                }
            }
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StencilItem {
    pub id: String,
    pub name: String,
    pub category: StencilCategory,
    pub default_label: String,
    pub default_value: String,
    pub default_width_mm: f64,
    pub default_height_mm: f64,
    pub default_layer: String,
    pub stroke_color: [u8; 4],
    pub fill_color: [u8; 4],
    pub stroke_width: f32,
    pub ports: Vec<ConnectionPort>,
    pub geometry: Vec<PrimOp>,
    pub is_dimension: bool,
    pub is_room_area: bool,
}

impl StencilItem {
    pub fn instantiate(&self, shape_id: u64, x: f64, y: f64, instance_num: usize) -> DiagramShape {
        let label = if self.default_label.ends_with('?') {
            format!("{}{}", self.default_label.trim_end_matches('?'), instance_num)
        } else {
            self.default_label.clone()
        };

        DiagramShape {
            id: shape_id,
            stencil_id: self.id.clone(),
            name: self.name.clone(),
            label,
            value: self.default_value.clone(),
            x,
            y,
            width: self.default_width_mm,
            height: self.default_height_mm,
            rotation_deg: 0.0,
            flip_x: false,
            flip_y: false,
            stroke_color: self.stroke_color,
            fill_color: self.fill_color,
            stroke_width: self.stroke_width,
            dashed: false,
            layer: self.default_layer.clone(),
            ports: self.ports.clone(),
            geometry: self.geometry.clone(),
            properties: Vec::new(),
            is_dimension: self.is_dimension,
            is_room_area: self.is_room_area,
            locked: false,
        }
    }
}


pub fn instantiate_shape(
    stencil_id: &str,
    shape_id: u64,
    x: f64,
    y: f64,
    instance_num: usize,
) -> Option<DiagramShape> {
    let normalized = match stencil_id {
        "plc_block" => "net_plc".to_string(),
        "fp_door_single" => "floor_door_right".to_string(),
        "fp_sink" => "furn_sink_kitchen".to_string(),
        "fp_table_chairs" => "furn_table_dining".to_string(),
        "fp_stove" => "furn_stove".to_string(),
        "fp_wc" => "furn_wc".to_string(),
        "fp_sauna_stove" => "furn_sauna_stove".to_string(),
        "fp_sofa" => "furn_sofa".to_string(),
        "fp_bed_double" => "furn_bed_double".to_string(),
        s if s.starts_with("iec_") => format!("elec_{}", &s[4..]),
        s if s.starts_with("sfs_") => format!("inst_{}", &s[4..]),
        s if s.starts_with("fp_") => format!("floor_{}", &s[3..]),
        s => s.to_string(),
    };
    builtin_stencils()
        .into_iter()
        .find(|s| s.id == normalized || s.id == stencil_id)
        .map(|s| s.instantiate(shape_id, x, y, instance_num))
}
